"""Запрос с шифром обслуживается перечнем из базы, а не поиском по смыслу.

Основание — ревью Codex 11.09.2026. На «ГЭСНм08-02-395» векторный поиск отвечал
`ГЭСНм20-02-002-14` и `ГЭСН28-02-022-05`, цепляясь за цифры в чужих шифрах: модель,
пришедшая посмотреть варианты таблицы, получала выдумку вместо перечня.
"""

from __future__ import annotations

import pytest

from proxy.smeta_core.norm_browser import code_lookup_request


@pytest.mark.parametrize(
    ("query", "expected"),
    [
        # Шифр таблицы: три группы цифр, ответом должны быть все её варианты.
        ("ГЭСНм08-02-395", ("ГЭСНм", "08-02-395")),
        # Полный шифр: четыре группы, ответом одна норма.
        ("ГЭСНм11-04-028-01", ("ГЭСНм", "11-04-028-01")),
        # Часть сборника отделяется от номера: в базе они в разных колонках, и без
        # разбора «08-02-395» совпадает и с ГЭСНм08, и с ГЭСН08.
        ("ГЭСН31-01-055-04", ("ГЭСН", "31-01-055-04")),
        ("ГЭСНр67-03-001-01", ("ГЭСНр", "67-03-001-01")),
        ("ГЭСНп02-02-003-01", ("ГЭСНп", "02-02-003-01")),
        # Территориальная и федеральная расценки указывают на ту же таблицу: в активной
        # базе лежат ГЭСН, и отвечать на них отказом значило бы прятать существующую норму.
        ("ТЕРм10-01-055", ("ГЭСНм", "10-01-055")),
        ("ФЕРм08-02-148-01", ("ГЭСНм", "08-02-148-01")),
        # Шифр внутри фразы — тоже обращение к норме, а не поиск по смыслу.
        ("покажи норму ГЭСНм08-02-395 целиком", ("ГЭСНм", "08-02-395")),
        ("Варианты таблицы (ГЭСНм10-01-052) какие?", ("ГЭСНм", "10-01-052")),
    ],
)
def test_code_is_recognised_in_the_query(query: str, expected: tuple[str, str]) -> None:
    assert code_lookup_request(query) == expected


@pytest.mark.parametrize(
    "query",
    [
        # Обычный запрос по смыслу обязан идти прежним путём.
        "прокладка кабеля в лотке",
        "Кабель витая пара неэкранированная U/UTP категория 5e",
        "",
        # Номер не той длины — не шифр: принять его значило бы искать несуществующее.
        "ГЭСНм08-02-3951",
        "ГЭСНм08-02-39",
        "ГЭСН8-02-395",
        # Цифры без семейства ничего не адресуют: под «08-02-395» есть нормы в разных
        # сборниках, и выбрать один из них было бы догадкой.
        "08-02-395",
    ],
)
def test_a_query_without_a_code_is_left_to_the_search(query: str) -> None:
    assert code_lookup_request(query) is None


def test_the_code_is_not_taken_from_inside_a_longer_token() -> None:
    """Шифр, склеенный с текстом, чаще всего опечатка, а не адрес нормы."""
    assert code_lookup_request("хГЭСНм08-02-395") is None
    assert code_lookup_request("ГЭСНм08-02-395х") is None


def test_a_code_answer_is_not_seen_as_a_blocked_search() -> None:
    """Исследование модели требует ветку `rag` со статусом «ok» — иначе весь проход 503.

    Воспроизведено живым прогоном 11.09: стоило модели написать шифр в запросе, как
    проход падал с `MODEL_RAG_SEARCH_INCOMPLETE`. Поиск здесь действительно не
    выполнялся, и это сказано полем `used`, но препятствий нет: ответ взят из базы.
    """
    from proxy.smeta_core.norm_browser import browse_norms_many

    answer = browse_norms_many(["ГЭСНм08-02-395"], limit=3)["ГЭСНм08-02-395"]
    rag = (answer.get("retrieval_trace") or {}).get("rag") or {}
    assert rag.get("status") == "ok"
    assert str(rag.get("collection") or "").strip()
    assert rag.get("used") is False
