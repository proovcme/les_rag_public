def test_fire_safety_wins_over_security_by_rule_order():
    """«Автоматизация противопожарной защиты» не должна попадать в охранные системы."""
    assert section_for_title("Автоматизация противопожарной защиты. Книга 2") == "fire_safety"
    assert section_for_title("Объектовая охранная сигнализация. Книга 2") == "security"


def test_titles_are_human_readable_for_reports():
    assert "СКС" in section_title("communications")
    assert section_title("нет такого") == "нет такого"


@pytest.mark.parametrize(
    ("title", "expected"),
    [
        # СКУД пишут и коротко, без слова «доступом» — в архиве это файлы КИТСО СКУД1.
        ("Система контроля и управления. 36 этаж здания «Башня»", "security"),
        ("Демонтаж. Система контроля и управления доступом", "security"),
        # А эти — не охрана, хотя формулировка почти та же.
        ("Система контроля и управления вентиляцией", "hvac"),
        ("Система контроля и управления инженерными системами", "automation"),
        ("Система контроля и управления освещением", "automation"),
        ("Система контроля и управления холодоснабжением", "hvac"),
    ],
)
def test_short_skud_name_does_not_swallow_engineering_systems(title, expected):
    """Ревью 10.09: «систем контрол и управлен» уводило вентиляцию в охрану."""
    assert section_for_title(title) == expected


def test_file_cipher_does_not_override_an_explicit_engineering_title():
    """Имя файла подсказывает раздел, но названный в шапке предмет сильнее."""
    from proxy.smeta_core.section_taxonomy import classify_estimate

    assert classify_estimate("Система контроля и управления вентиляцией", "02-03-03 ОВ.xlsx") == "hvac"
