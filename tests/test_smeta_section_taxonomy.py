"""Разбор номеров и наименований локальных смет.

Все примеры — из объектных смет архива: 177 файлов, 697 пар «номер → наименование»,
237 различных систем. Раньше классификатор читал шифры в именах файлов, и 1 534 файла
из 2 283 попадали в «прочее»: одна система пишется «ОВ», «ОВиК», «АППЗ», «СПД».
"""

from __future__ import annotations

import pytest

from proxy.smeta_core.section_taxonomy import (
    parse_estimate_number,
    section_for_title,
    section_title,
    strip_cost_prefix,
)


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # Локальные сметы: три сегмента, редакция через «и».
        ("01-01-17.1и1 СКС.СС", {"number": "01-01-17.1", "stage": "01", "chapter": "01",
                                 "item": "17", "work_kind": "demolition", "revision": "1"}),
        ("02-08-03 СКС.СС", {"number": "02-08-03", "stage": "02", "chapter": "08",
                             "item": "03", "work_kind": "installation", "revision": ""}),
        ("09-06-01 ПНР СЗИ СС Б6 v3", {"number": "09-06-01", "stage": "09", "chapter": "06",
                                       "item": "01", "work_kind": "commissioning", "revision": ""}),
        ("14-05-04 Мини-кухни+техника Б1 v6", {"number": "14-05-04", "stage": "14", "chapter": "05",
                                               "item": "04", "work_kind": "equipment", "revision": ""}),
        # Объектная смета: два сегмента, третьего нет.
        ("02-10 Э25.2 v5 - ОС", {"number": "02-10", "stage": "02", "chapter": "10",
                                 "item": "", "work_kind": "installation", "revision": ""}),
        ("без номера", {}),
        # Год в названии — не номер сметы.
        ("Смета 2023-2024 годов", {}),
    ],
)
def test_estimate_number_carries_the_work_kind(text, expected):
    """Первый сегмент номера — вид работ: 01 демонтаж, 02 монтаж, 09 пусконаладка."""
    assert parse_estimate_number(text) == expected


@pytest.mark.parametrize(
    ("title", "expected"),
    [
        ("Демонтаж. Структурированная кабельная система", "Структурированная кабельная система"),
        ("Монтаж. Вентиляция и кондиционирование. Дооснащение", "Вентиляция и кондиционирование. Дооснащение"),
        ("ЗИП Система оповещения и управления эвакуацией", "Система оповещения и управления эвакуацией"),
        ("Оборудование. Система охранная телевизионная", "Система охранная телевизионная"),
        ("ПО, необлагаемое НДС", "необлагаемое НДС"),
        ("Холодоснабжение", "Холодоснабжение"),
    ],
)
def test_cost_prefix_is_not_a_section(title, expected):
    """«ЗИП», «ПНР», «Оборудование» — тип затрат; раздел задаёт система следом."""
    assert strip_cost_prefix(title) == expected


